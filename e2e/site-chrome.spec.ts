test.afterAll(async () => prisma.$disconnect());

async function login(page: Page, email: string) {
  const response = await page.request.post('/api/auth/login', { data: { email, password } });
  expect(response.ok(), await response.text()).toBeTruthy();
}

async function csrfHeaders(page: Page) {
  const cookies = await page.context().cookies();
  const csrf = cookies.find(cookie => cookie.name === 'marketplace_csrf')?.value;
  expect(csrf).toBeTruthy();
  return { 'x-csrf-token': csrf! };
}

test('admin can customize, preview, publish and serve responsive site chrome', async ({ page }) => {
  await login(page, adminEmail);
  const originalResponse = await page.request.get('/api/admin/site-chrome');
  expect(originalResponse.ok(), await originalResponse.text()).toBeTruthy();
  const originalRecord = await prisma.siteChromeConfiguration.findUnique({ where: { id: 'platform' } });
  expect(originalRecord, 'the isolated site-chrome test requires a clean platform chrome baseline').toBeNull();
  const headerTitle = `Chrome E2E ${Date.now()}`;
  const footerTitle = `Footer E2E ${Date.now()}`;

  try {
    await page.goto('/admin/platform?section=chrome');
    await expect(page.getByRole('heading', { name: 'Header & footer builder' })).toBeVisible();
    await page.getByRole('tab', { name: 'Header' }).click();
    await page.getByLabel('Brand title').fill(headerTitle);
    await page.getByLabel('Show working product/store search').check();
    await page.getByRole('tab', { name: 'Footer' }).click();
    await page.getByLabel('Short title').fill(footerTitle);
    await page.getByLabel('Short description').fill('Responsive footer generated by the isolated browser test.');
    await page.getByRole('tab', { name: 'Social media' }).click();
    await page.getByRole('button', { name: 'Add social account' }).click();
    await expect(page.getByText('1 / 6 accounts')).toBeVisible();
    await page.getByRole('tab', { name: 'Preview' }).click();
    await expect(page.locator('.siteChromePreview .siteChromeBrand')).toContainText(headerTitle);
    await page.getByLabel('Preview width').selectOption('mobile');
    await expect(page.locator('.siteChromePreview--mobile')).toBeVisible();

    page.once('dialog', dialog => { void dialog.accept(); });
    await page.getByRole('button', { name: 'Publish changes' }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Published. Open marketplace pages refresh' })).toBeVisible();
    await page.goto('/');
    await expect(page.locator('.siteChromeHeader .platformBrandName')).toHaveText(headerTitle);
    await expect(page.locator('.siteChromeHeader form[role="search"]')).toBeVisible();
    await expect(page.locator('.siteChromeFooter')).toContainText(footerTitle);
    await expect(page.getByRole('link', { name: /Cart/ })).toBeVisible();

    await page.goto('/admin/platform?section=chrome');
    await page.getByRole('tab', { name: 'Page visibility' }).click();
    await page.getByLabel('Suppress footer on Marketplace home').check();
    page.once('dialog', dialog => { void dialog.accept(); });
    await page.getByRole('button', { name: 'Publish changes' }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Published. Open marketplace pages refresh' })).toBeVisible();
    await page.goto('/');
    await expect(page.locator('.siteChromeFooter')).toHaveCount(0);
    await expect(page.locator('.platformLegalDisclosure')).toBeVisible();

    await page.goto('/admin/platform?section=chrome');
    await page.getByRole('tab', { name: 'Page visibility' }).click();
    await page.getByLabel('Suppress footer on Marketplace home').uncheck();
    page.once('dialog', dialog => { void dialog.accept(); });
    await page.getByRole('button', { name: 'Publish changes' }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Published. Open marketplace pages refresh' })).toBeVisible();
    await page.goto('/');
    await expect(page.locator('.siteChromeFooter')).toBeVisible();
    for (const width of [320, 390, 768, 1024] as const) {
      await page.setViewportSize({ width, height: 900 });
      await page.reload();
      const headerWidth = await page.locator('.siteChromeHeader').evaluate(element => ({ scroll: element.scrollWidth, client: element.clientWidth }));
      expect(headerWidth.scroll, `custom header should not overflow at ${width}px`).toBeLessThanOrEqual(headerWidth.client + 1);
      const footerWidth = await page.locator('.siteChromeFooter').evaluate(element => ({ scroll: element.scrollWidth, client: element.clientWidth }));
      expect(footerWidth.scroll, `custom footer should not overflow at ${width}px`).toBeLessThanOrEqual(footerWidth.client + 1);
    }
  } finally {
    await prisma.siteChromeRevision.deleteMany({ where: { configurationId: 'platform' } });
    await prisma.siteChromeConfiguration.deleteMany({ where: { id: 'platform' } });
  }
});

test('legacy/free seller can view the builder but cannot save or publish premium chrome', async ({ page }) => {
  await login(page, sellerEmail);
  await page.goto('/seller/site-chrome');
  await expect(page.getByRole('heading', { name: 'Header & footer builder' })).toBeVisible();
  await expect(page.getByText('A paid Store Plan is required to publish custom site chrome.')).toBeVisible();
  const response = await page.request.get('/api/seller/site-chrome');
  expect(response.ok(), await response.text()).toBeTruthy();
  const state = await response.json() as { eligible: boolean; draft: unknown; draftVersion: number };
  expect(state.eligible).toBe(false);
  const save = await page.request.put('/api/seller/site-chrome', {
    data: { expectedVersion: state.draftVersion, configuration: state.draft, reason: 'Verify free-plan restriction' },
    headers: await csrfHeaders(page)
  });
  expect(save.status()).toBe(403);
  const publish = await page.request.post('/api/seller/site-chrome/publish', {
    data: { expectedVersion: state.draftVersion },
    headers: await csrfHeaders(page)
  });
  expect(publish.status()).toBe(403);
});

const captureDirectory = process.env.SITE_CHROME_CAPTURE_DIR;
if (captureDirectory) test('captures all six site chrome templates at desktop and mobile widths', async ({ page }) => {
  test.setTimeout(120_000);
  const output = resolve(captureDirectory);
  mkdirSync(output, { recursive: true });
  await login(page, adminEmail);
  const originalRecord = await prisma.siteChromeConfiguration.findUnique({ where: { id: 'platform' } });
  expect(originalRecord, 'screenshot capture requires a clean disposable platform chrome baseline').toBeNull();
  const baselineResponse = await page.request.get('/api/admin/site-chrome');
  expect(baselineResponse.ok(), await baselineResponse.text()).toBeTruthy();
  const baseline = (await baselineResponse.json() as { draft: SiteChromeConfiguration }).draft;
  const configuration: SiteChromeConfiguration = structuredClone(baseline);
  configuration.header.title = 'Market Lane';
  configuration.header.tagline = 'Independent marketplace';
  configuration.header.showSearch = true;
  configuration.footer.title = 'Market Lane';
  configuration.footer.description = 'A thoughtful marketplace for independent stores and the people who love them.';
  configuration.footer.sections = [{ id: 'explore', title: 'Explore', links: [{ id: 'browse', label: 'Browse the marketplace', href: '/', enabled: true }] }];
  configuration.footer.socials = [{ id: 'instagram', platform: 'INSTAGRAM', url: 'https://instagram.com/marketlane', label: 'Instagram', enabled: true, display: 'ICON_AND_LABEL' }];

  try {
    // The admin publish flow is covered above; this opt-in visual pass seeds only the guarded disposable DB.
    const setPublishedConfiguration = async () => {
      await prisma.siteChromeConfiguration.upsert({
        where: { id: 'platform' },
        create: { id: 'platform', storeId: null, draftJson: configuration, publishedJson: configuration, draftVersion: 1, publishedVersion: 1, publishedAt: new Date() },
        update: { draftJson: configuration, publishedJson: configuration, draftVersion: 1, publishedVersion: 1, publishedAt: new Date() }
      });
      const response = await page.request.get('/api/site-chrome/public?kind=HOME');
      expect(response.ok(), await response.text()).toBeTruthy();
      const publicState = await response.json() as { configuration: SiteChromeConfiguration | null };
      expect(publicState.configuration?.header.template).toBe(configuration.header.template);
      expect(publicState.configuration?.footer.template).toBe(configuration.footer.template);
    };
    const capturePublicChrome = async (kind: 'header' | 'footer', name: string, template: string) => {
      for (const [width, height, label] of [[1440, 1000, 'desktop'], [390, 844, 'mobile']] as const) {
        await page.setViewportSize({ width, height });
        await page.goto('/');
        const target = page.locator(kind === 'header' ? '.siteChromeHeader' : '.siteChromeFooter');
        await expect(target).toHaveClass(new RegExp(`siteChrome${kind === 'header' ? 'Header' : 'Footer'}--${template.toLowerCase()}`));
        await expect(target).toBeVisible();
        if (kind === 'footer') await expect(target).toContainText('A thoughtful marketplace for independent stores');
        await target.scrollIntoViewIfNeeded();
        await target.screenshot({ path: join(output, `${kind}-${name}-${label}.png`), animations: 'disabled' });
      }
    };

    for (const [id, name] of [['CLASSIC', 'classic-marketplace'], ['EDITORIAL', 'editorial-premium'], ['COMMERCE', 'commerce-pro']] as const) {
      configuration.header.template = id;
      await setPublishedConfiguration();
      await capturePublicChrome('header', name, id);
    }
    for (const [id, name] of [['MINIMAL', 'minimal-classic'], ['BUSINESS', 'business-columns'], ['SIGNATURE', 'signature-brand']] as const) {
      configuration.footer.template = id;
      await setPublishedConfiguration();
      await capturePublicChrome('footer', name, id);
    }
  } finally {
    await prisma.siteChromeRevision.deleteMany({ where: { configurationId: 'platform' } });
    await prisma.siteChromeConfiguration.deleteMany({ where: { id: 'platform' } });
  }
});
